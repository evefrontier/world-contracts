/**
 * Write [published.<env>] into a package's Published.toml from a publish/upgrade
 * result. `sui client publish|upgrade` does this itself, but not when the tx is
 * signed outside the CLI (KMS), so the deploy scripts call this instead.
 *
 * Usage: tsx ts-scripts/record-published.ts <pkgDir> <env> <chainId> <result.json>
 */
import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parse as parseToml } from '@iarna/toml'

type ObjectChange = {
  type: string
  packageId?: string
  version?: string
  objectId?: string
  objectType?: string
}

type Entry = {
  'original-id'?: string
  'upgrade-capability'?: string
  'build-config'?: { flavor?: string; edition?: string }
}

const HEADER = `# Generated by Move
# This file contains metadata about published versions of this package in different environments
# This file SHOULD be committed to source control
`

const [pkgDir, env, chainId, resultPath] = process.argv.slice(2)
if (!pkgDir || !env || !chainId || !resultPath) {
  console.error(
    'Usage: record-published.ts <pkgDir> <env> <chainId> <result.json>',
  )
  process.exit(1)
}

const changes: ObjectChange[] =
  JSON.parse(readFileSync(resultPath, 'utf8')).objectChanges ?? []
const published = changes.find((c) => c.type === 'published')
if (!published?.packageId || !published.version) {
  throw new Error(`no published package in ${resultPath}`)
}

const file = join(pkgDir, 'Published.toml')
const text = existsSync(file) ? readFileSync(file, 'utf8') : HEADER
const existing = (parseToml(text) as { published?: Record<string, Entry> })
  .published?.[env]

// A fresh publish creates the UpgradeCap; an upgrade reuses the recorded one.
const createdCap = changes.find(
  (c) => c.type === 'created' && c.objectType === '0x2::package::UpgradeCap',
)?.objectId
const upgradeCap = createdCap ?? existing?.['upgrade-capability']
if (!upgradeCap) throw new Error(`no UpgradeCap for ${pkgDir}/${env}`)
const originalId = createdCap
  ? published.packageId
  : (existing?.['original-id'] ?? published.packageId)

const moveToml = parseToml(readFileSync(join(pkgDir, 'Move.toml'), 'utf8')) as {
  package?: { edition?: string }
}
const toolchain = execFileSync('sui', ['--version'], { encoding: 'utf8' })
  .trim()
  .replace(/^sui\s+/, '')
  .replace(/-.*$/, '')

const section = `[published.${env}]
chain-id = "${chainId}"
published-at = "${published.packageId}"
original-id = "${originalId}"
version = ${published.version}
toolchain-version = "${toolchain}"
build-config = { flavor = "${existing?.['build-config']?.flavor ?? 'sui'}", edition = "${moveToml.package?.edition ?? '2024'}" }
upgrade-capability = "${upgradeCap}"
`

const header = `[published.${env}]`
const start = text.indexOf(header)
let out: string
if (start === -1) {
  out = `${text.trimEnd()}\n\n${section}`
} else {
  const next = text.slice(start + header.length).search(/^\[/m)
  const end = next === -1 ? text.length : start + header.length + next
  out = `${text.slice(0, start)}${section}${next === -1 ? '' : `\n${text.slice(end)}`}`
}
writeFileSync(file, out)
console.log(`Recorded [published.${env}] in ${file}`)
